import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const sourcePath = fileURLToPath(new URL('../../src/v2/app/design/tokens.json', import.meta.url));
const outputPath = fileURLToPath(new URL('../../src/v2/app/design/tokens.ts', import.meta.url));

function valueMap(tokens) {
  return Object.fromEntries(tokens.map(({ name, value }) => [name, value]));
}

function typeMap(type) {
  return Object.fromEntries(
    type.groups.flatMap((group) => group.styles.map((style) => [
      style.name,
      Object.fromEntries([
        ['family', style.family ?? group.family],
        ['fontSize', style.fontSize],
        ['lineHeight', style.lineHeight],
        ['fontWeight', style.fontWeight],
        ['letterSpacing', style.letterSpacing],
      ].filter(([, value]) => value !== undefined)),
    ])),
  );
}

export function generateTokens(source) {
  const themes = Object.fromEntries(
    source.color.themes.map((theme) => [theme.id, valueMap(source.color.tokens)]),
  );
  const payload = {
    colors: themes,
    spacing: valueMap(source.spacing.tokens),
    radius: valueMap(source.radius.tokens),
    shadow: valueMap(source.shadow.tokens),
    type: {
      families: source.type.families,
      styles: typeMap(source.type),
    },
  };
  return [
    '// GENERATED by tools/design/gen-tokens.mjs from tokens.json - do not edit',
    '',
    `export const colors = ${JSON.stringify(payload.colors, null, 2)} as const;`,
    `export const spacing = ${JSON.stringify(payload.spacing, null, 2)} as const;`,
    `export const radius = ${JSON.stringify(payload.radius, null, 2)} as const;`,
    `export const shadow = ${JSON.stringify(payload.shadow, null, 2)} as const;`,
    `export const type = ${JSON.stringify(payload.type, null, 2)} as const;`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = JSON.parse(await readFile(sourcePath, 'utf8'));
  await writeFile(outputPath, generateTokens(source), 'utf8');
}
