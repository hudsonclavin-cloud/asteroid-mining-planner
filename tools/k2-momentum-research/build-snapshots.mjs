// Regenerates the two data snapshots the K2 sim reads from file://.
//
//   node tools/k2-momentum-research/build-snapshots.mjs --skyhook <path-to-skyhook-repo>
//
// 1. rev-a-snapshot.js  — Skyhook params/rev_a.json copied VERBATIM, plus its sha256 and the
//    Skyhook commit it came from. The sim never carries a tether constant from memory.
// 2. vinf-proxy.js       — per-body minimum Earth-DEPARTURE v-inf from Aster's committed screening
//    cache (docs/lambert-screen-cache.json). This is an OUTBOUND quantity. It is a population-scale
//    proxy only; true Earth-ARRIVAL v-inf needs the K1 return-leg porkchop, which does not exist yet.

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const asterRoot = resolve(here, '..', '..');
const argIdx = process.argv.indexOf('--skyhook');
if (argIdx < 0) {
  console.error('usage: node build-snapshots.mjs --skyhook <path-to-skyhook-repo>');
  process.exit(2);
}
const skyhookRoot = resolve(process.argv[argIdx + 1]);

// ---- Rev A snapshot ----
const revAPath = join(skyhookRoot, 'params', 'rev_a.json');
const revARaw = readFileSync(revAPath);
const revASha = createHash('sha256').update(revARaw).digest('hex');
let skyhookCommit = 'UNKNOWN';
try {
  skyhookCommit = execFileSync('git', ['-C', skyhookRoot, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch { /* honest UNKNOWN */ }
const revA = JSON.parse(revARaw.toString('utf8'));
const revAOut =
  '// GENERATED by build-snapshots.mjs. Do not edit by hand.\n' +
  `// Source: skyhook params/rev_a.json @ ${skyhookCommit}\n` +
  `// sha256(rev_a.json) = ${revASha}\n` +
  'globalThis.REV_A_SNAPSHOT = ' + JSON.stringify({
    provenance: { source: 'skyhook/params/rev_a.json', skyhookCommit, sha256: revASha, snapshotAtUtc: new Date().toISOString() },
    params: revA
  }, null, 1) + ';\n';
writeFileSync(join(here, 'rev-a-snapshot.js'), revAOut);

// ---- v-inf proxy from Aster's screening cache ----
const cachePath = join(asterRoot, 'docs', 'lambert-screen-cache.json');
const cacheRaw = readFileSync(cachePath);
const cacheSha = createHash('sha256').update(cacheRaw).digest('hex');
const cache = JSON.parse(cacheRaw.toString('utf8'));
const c3Max = cache.metadata.feasibleC3MaxKm2S2;
const BIN = 0.25, MAXV = 8;
const bins = new Array(Math.round(MAXV / BIN)).fill(0);
let counted = 0, overflow = 0, noWindow = 0;
const sample = [];
for (const b of cache.bodies) {
  const ws = (b.bestWindows || []).filter((w) => Number.isFinite(w.vInfDep) && w.c3 <= c3Max);
  if (!ws.length) { noWindow++; continue; }
  const best = ws.reduce((x, y) => (y.vInfDep < x.vInfDep ? y : x));
  counted++;
  const k = Math.floor(best.vInfDep / BIN);
  if (k >= bins.length) overflow++; else bins[k]++;
  if (sample.length < 12 && best.vInfDep < 1.2) sample.push({ designation: b.designation, vInfDep: +best.vInfDep.toFixed(3), launchDate: best.launchDate, tofDays: best.tofDays });
}
const proxyOut =
  '// GENERATED by build-snapshots.mjs. Do not edit by hand.\n' +
  '// OUTBOUND Earth-departure v-inf (min per body, C3 <= feasibleC3Max). NOT return-leg arrival v-inf.\n' +
  'globalThis.VINF_PROXY = ' + JSON.stringify({
    provenance: {
      source: 'asteroid-mining-planner/docs/lambert-screen-cache.json',
      sha256: cacheSha,
      cacheGeneratedAt: cache.metadata.generatedAt,
      solverCommit: cache.metadata.provenance.solverCommit,
      screeningWindow: cache.metadata.screeningWindow,
      feasibleC3MaxKm2S2: c3Max
    },
    caveat: 'Outbound departure v-inf, min over the cached best windows per body. Earth-arrival v-inf for a body->Earth leg is a different quantity (K1). Shown for population scale only. [Speculative as a proxy]',
    binKms: BIN, bins, overflow, counted, noWindow, catalogSize: cache.bodies.length, lowestSample: sample
  }, null, 1) + ';\n';
writeFileSync(join(here, 'vinf-proxy.js'), proxyOut);

console.log(`rev-a-snapshot.js  skyhook@${skyhookCommit.slice(0, 7)} sha256=${revASha.slice(0, 12)}…`);
console.log(`vinf-proxy.js      ${counted} bodies binned, ${noWindow} with no window under C3<=${c3Max}, ${overflow} above ${MAXV} km/s`);
